private void loadOrderSummary() {
    StringBuilder summary = new StringBuilder();
    double total = 0;

    for (int i = 0; i < OrderData.productNames.size(); i++) {
        String name = OrderData.productNames.get(i);
        double price = OrderData.productPrices.get(i);
        int quantity = OrderData.quantities.get(i);
        double subtotal = price * quantity;

        summary.append(name)
               .append(" x ")
               .append(quantity)
               .append(" = P")
               .append(String.format("%.2f", subtotal))
               .append("\n");

        total += subtotal;
    }

    summary.append("\nTOTAL: P")
           .append(String.format("%.2f", total));

    txtOrderSummary.setText(summary.toString());
}


