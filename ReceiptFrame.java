    private void displayReceipt() {
    StringBuilder receipt = new StringBuilder();

    receipt.append("        DUNKIN'\n");
    receipt.append("      ORDER RECEIPT\n");
    receipt.append("================================\n\n");

    receipt.append("Order Number: ")
           .append(orderId > 0 ? orderId : "Not available")
           .append("\n");

    receipt.append("Customer Name: ")
           .append(UserSession.username == null
                   ? "Customer" : UserSession.username)
           .append("\n");

    receipt.append("Order Date: ")
           .append(java.time.LocalDate.now())
           .append("\n");

    receipt.append("Payment Method: ")
           .append(paymentMethod == null
                   ? "Not available" : paymentMethod)
           .append("\n");

    receipt.append("Reference Number: ")
           .append(referenceNumber == null
                   ? "Not available" : referenceNumber)
           .append("\n");

    receipt.append("--------------------------------\n");
    receipt.append("ORDER DETAILS\n");
    receipt.append("--------------------------------\n");

    for (int i = 0; i < OrderData.productNames.size(); i++) {
        String name = OrderData.productNames.get(i);
        double price = OrderData.productPrices.get(i);
        int quantity = OrderData.quantities.get(i);

        receipt.append(name).append("\n");
        receipt.append("  ")
               .append(quantity)
               .append(" x P")
               .append(String.format("%.2f", price))
               .append(" = P")
               .append(String.format("%.2f", price * quantity))
               .append("\n\n");
    }

    receipt.append("--------------------------------\n");

    if (subtotal != null) {
        receipt.append("Subtotal: P")
               .append(subtotal.toPlainString())
               .append("\n");
    }

    if (discount != null) {
        receipt.append("Discount: -P")
               .append(discount.toPlainString())
               .append("\n");
    }

    if (total != null) {
        receipt.append("TOTAL AMOUNT: P")
               .append(total.toPlainString())
               .append("\n");
    } else {
        receipt.append("TOTAL AMOUNT: P")
               .append(String.format("%.2f", OrderData.getTotal()))
               .append("\n");
    }

    receipt.append("--------------------------------\n");
    receipt.append("Payment Status: PENDING VERIFICATION\n");
    receipt.append("Order Status: PENDING\n\n");
    receipt.append("Thank you for ordering!\n");
    receipt.append("       Come again!");

    txtReceipt.setText(receipt.toString());
    txtReceipt.setEditable(false);
    txtReceipt.setCaretPosition(0);
}

