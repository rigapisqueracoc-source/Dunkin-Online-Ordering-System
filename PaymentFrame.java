    private void btnPayNowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayNowActionPerformed
        String reference = txtReference.getText().trim();

if (!reference.matches("[0-9]{13}")) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter a complete 13-digit reference number.",
        "Invalid Reference Number",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

    if (UserSession.userId <= 0 ||
        !"CUSTOMER".equalsIgnoreCase(UserSession.role)) {
        JOptionPane.showMessageDialog(
            this, "Please log in with a customer account.");
        return;
    }

    selectedPaymentMethod =
        rdoGCash.isSelected() ? "GCash" : "Maya";

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Payment Method: " + selectedPaymentMethod +
        "\nReference Number: " + reference +
        "\n\nSubmit this order for payment verification?",
        "Confirm Order",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String findProduct =
    "SELECT product_id, price, discount, stock FROM products " +
    "WHERE product_name = ? AND available = 1 FOR UPDATE";

    String insertOrder =
    "INSERT INTO orders " +
    "(customer_id, subtotal, discount_amount, total_amount, " +
    "payment_method, payment_status, order_status, reference_number) " +
    "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";
    
    
String insertItem =
    "INSERT INTO order_items " +
    "(order_id, product_id, quantity, price, discount) " +
    "VALUES (?, ?, ?, ?, ?)";


    Connection con = null;

    try {
        con = dunkin.database.DatabaseConnection.getConnection();
        con.setAutoCommit(false);

        BigDecimal subtotal = BigDecimal.ZERO;
        BigDecimal discountTotal = BigDecimal.ZERO;

        // Match every cart item to a product in the database.
        try (PreparedStatement find = con.prepareStatement(findProduct)) {
            for (int i = 0; i < OrderData.productNames.size(); i++) {
                find.setString(1, OrderData.productNames.get(i));

                try (ResultSet rs = find.executeQuery()) {
                    if (!rs.next()) {
                        throw new SQLException(
                            "Product not found or unavailable: " +
                            OrderData.productNames.get(i));
                    }

                    BigDecimal price = rs.getBigDecimal("price");
                    BigDecimal rate = rs.getBigDecimal("discount");
                    if (rate == null) rate = BigDecimal.ZERO;

                    int quantity = OrderData.quantities.get(i);
int stock = rs.getInt("stock");

if (quantity <= 0) {
    throw new SQLException("Invalid product quantity.");
}

if (stock < quantity) {
    throw new SQLException(
        "Not enough stock for " +
        OrderData.productNames.get(i) +
        ". Available stock: " + stock
    );
}

                    BigDecimal lineSubtotal =
                        price.multiply(BigDecimal.valueOf(quantity));

                    BigDecimal lineDiscount =
                        lineSubtotal.multiply(rate)
                            .divide(new BigDecimal("100"), 2,
                                java.math.RoundingMode.HALF_UP);

                    subtotal = subtotal.add(lineSubtotal);
                    discountTotal = discountTotal.add(lineDiscount);
                }
            }
        }

        BigDecimal total = subtotal.subtract(discountTotal);

        // Save the order first to generate its order ID.
        int orderId;

        try (PreparedStatement order = con.prepareStatement(
        insertOrder, Statement.RETURN_GENERATED_KEYS)) {

           order.setInt(1, UserSession.userId);
order.setBigDecimal(2, subtotal);
order.setBigDecimal(3, discountTotal);
order.setBigDecimal(4, total);
order.setString(5, selectedPaymentMethod);
order.setString(6, "PENDING VERIFICATION");
order.setString(7, "PENDING");
order.setString(8, reference);;

    order.executeUpdate();


            try (ResultSet keys = order.getGeneratedKeys()) {
                 if (!keys.next()) {
            throw new SQLException("Could not create order ID.");
        }
        orderId = keys.getInt(1);
    }
        }

        // Save each item using its database product ID.
        try (PreparedStatement find = con.prepareStatement(findProduct);
     PreparedStatement item = con.prepareStatement(insertItem);
     PreparedStatement stockUpdate = con.prepareStatement(
         "UPDATE products SET stock = stock - ? " +
         "WHERE product_id = ? AND available = 1 AND stock >= ?")) {

            for (int i = 0; i < OrderData.productNames.size(); i++) {
                find.setString(1, OrderData.productNames.get(i));

                try (ResultSet rs = find.executeQuery()) {
                    if (!rs.next()) {
                        throw new SQLException("Product not found.");
                    }

                    BigDecimal price = rs.getBigDecimal("price");
                    BigDecimal rate = rs.getBigDecimal("discount");
                    if (rate == null) rate = BigDecimal.ZERO;

                    BigDecimal lineDiscount =
                        price.multiply(BigDecimal.valueOf(
                            OrderData.quantities.get(i)))
                            .multiply(rate)
                            .divide(new BigDecimal("100"), 2,
                                java.math.RoundingMode.HALF_UP);

                    item.setInt(1, orderId);
                    item.setInt(2, rs.getInt("product_id"));
                    item.setInt(3, OrderData.quantities.get(i));
                    item.setBigDecimal(4, price);
                    item.setBigDecimal(5, lineDiscount);
                    
                    item.executeUpdate();
                    
                    // Deduct the ordered quantity from stock.
int quantity = OrderData.quantities.get(i);

stockUpdate.setInt(1, quantity);
stockUpdate.setInt(2, rs.getInt("product_id"));
stockUpdate.setInt(3, quantity);

int updated = stockUpdate.executeUpdate();

if (updated != 1) {
    throw new SQLException(
        "Insufficient stock for " +
        OrderData.productNames.get(i) +
        ". Please try again."
    );
}
                }
            }
        }
        
        

        con.commit();
        
        OrderData.clearCart();

        ReceiptFrame receipt = new ReceiptFrame(
    orderId,
    reference,
    selectedPaymentMethod,
    subtotal,
    discountTotal,
    total
);

receipt.setLocationRelativeTo(null);
receipt.setVisible(true);
this.dispose();

    } catch (Exception e) {
        if (con != null) {
            try {
                con.rollback();
            } catch (SQLException rollbackError) {
                e.addSuppressed(rollbackError);
            }
        }

        JOptionPane.showMessageDialog(
            this, "Order could not be saved: " + e.getMessage());
    } finally {
        if (con != null) {
            try {
                con.setAutoCommit(true);
                con.close();
            } catch (SQLException ignored) {
            }
        }
    }
    }//GEN-LAST:event_btnPayNowActionPerformed

