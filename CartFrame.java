    private void btnRemoceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoceActionPerformed
        
int row = tblCart.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please select an item to remove."
    );
    return;
}

OrderData.productNames.remove(row);
OrderData.productPrices.remove(row);
OrderData.quantities.remove(row);

loadCart();

javax.swing.JOptionPane.showMessageDialog(
    this, "Item removed from cart."
);

    }//GEN-LAST:event_btnRemoceActionPerformed

