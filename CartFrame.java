    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed

    // Check whether a product row is selected
    int row = tblCart.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a product from your cart first."
        );
        return;
    }

    // Convert selected row to the table model row
    int modelRow = tblCart.convertRowIndexToModel(row);

    // Column 3 is Quantity (Java index 2)
    Object currentQuantity = tblCart.getModel().getValueAt(modelRow, 2);

    String input = JOptionPane.showInputDialog(
        this,
        "Enter the new quantity:",
        currentQuantity
    );

    // Cancel was clicked
    if (input == null) {
        return;
    }

    try {
        int quantity = Integer.parseInt(input.trim());

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "Quantity must be at least 1."
            );
            return;
        }

        // Check that the selected row exists in OrderData
        if (modelRow >= OrderData.quantities.size()) {
            JOptionPane.showMessageDialog(
                this,
                "Cart data does not match the table. Please refresh your cart."
            );
            return;
        }

        // Update the shared cart quantity
        OrderData.quantities.set(modelRow, quantity);

        // Update the quantity displayed in the table
        tblCart.getModel().setValueAt(quantity, modelRow, 2);

        // Refresh total if you have a total label
        double total = OrderData.getTotal();

        JOptionPane.showMessageDialog(
            this,
            "Quantity updated successfully!\n"
            + "New cart total: ₱"
            + String.format("%.2f", total)
        );

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this,
            "Invalid quantity. Please enter a whole number, such as 2 or 3."
        );
    }

    }//GEN-LAST:event_btnEditActionPerformed

