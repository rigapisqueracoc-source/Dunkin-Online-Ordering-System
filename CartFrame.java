    private void loadCart() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblCart.getModel();

    model.setRowCount(0);

    double total = 0;

    for (int i = 0; i < OrderData.productNames.size(); i++) {
        String product = OrderData.productNames.get(i);
        double price = OrderData.productPrices.get(i);
        int quantity = OrderData.quantities.get(i);
        double subtotal = price * quantity;

        model.addRow(new Object[]{
            product, price, quantity, subtotal
        });

        total += subtotal;
    }

    lblTotal.setText("TOTAL: ₱" + String.format("%.2f", total));
}
