    private void SignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SignUpActionPerformed

    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter a username and password.");
        return;
    }

    if (password.length() < 8) {
        JOptionPane.showMessageDialog(this,
                "Password must be at least 8 characters.");
        return;
    }

    String url = "jdbc:mysql://localhost:3306/dunkin_ordering";
    String dbUser = "root";
    String dbPassword = "";

    String checkSql =
            "SELECT user_id FROM users WHERE username = ?";
    String insertSql =
            "INSERT INTO users (username, password, role) VALUES (?, ?, ?)";

    try (java.sql.Connection con =
            java.sql.DriverManager.getConnection(url, dbUser, dbPassword)) {

        try (java.sql.PreparedStatement check =
                con.prepareStatement(checkSql)) {

            check.setString(1, username);

            try (java.sql.ResultSet rs = check.executeQuery()) {
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this,
                            "Username already exists.");
                    return;
                }
            }
        }

        try (java.sql.PreparedStatement pst =
                con.prepareStatement(insertSql)) {

            pst.setString(1, username);
            pst.setString(2, password);
            pst.setString(3, "CUSTOMER");

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "Account created successfully!");

            LoginFrame login = new LoginFrame();
            login.setVisible(true);
            this.dispose();
        }

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage());
    }

    }//GEN-LAST:event_SignUpActionPerformed

